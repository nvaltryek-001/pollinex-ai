import { CartesianGrid, Line, LineChart, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { Card, Empty, ErrorBanner, Loading, Notice, PageHeader, Stat } from "../components/ui";
import { label, num, pct, useApi, when } from "../lib/hooks";

/* eslint-disable @typescript-eslint/no-explicit-any */
type AnyObj = Record<string, any>;

export default function EvaluationPage() {
  const { data, error, loading, reload } = useApi<AnyObj>("/analytics/model-performance");
  const det = data?.detector_evaluation;
  const sp = data?.species_evaluation;
  const trade = data?.detector_inference_tradeoff;
  const yolo = data?.yolo11_evaluation;
  const ext = data?.species_extension_evaluation;
  const sunDet = data?.detector_on_tf_flower_detection_sunflower;
  const multi = data?.species_multi_evaluation;
  const yoloDec = data?.yolo11_deploy_decision;
  const dep = det ? det.variants[det.deployed_variant] : null;

  return (
    <div>
      <PageHeader kicker="Module 8 · measured, not claimed" title="AI model evaluation">
        All numbers below are read from evaluation reports generated by the training scripts on the held-out test split. Nothing here is a placeholder.
      </PageHeader>
      <ErrorBanner error={error} onRetry={reload} />
      {loading && <Loading />}
      {data && !data.available && <Empty title="No evaluation reports">{data.detail}</Empty>}
      {det && dep && (
        <div className="space-y-5">
          {yoloDec?.deployed && (
            <Card title="Deployed detector: YOLO11n (ONNX, CPU)" subtitle="trained on USDA apple/peach/pear + TF sunflower boxes; each test split held out and used once">
              <div className="grid grid-cols-2 gap-3 md:grid-cols-4">
                <Stat label="USDA test mAP@0.50" value={num(yoloDec.usda_test.yolo11.mAP50, 3)} hint={`pixel model ${num(yoloDec.usda_test.pixel.mAP50, 3)}`} />
                <Stat label="USDA test mAP@0.50:0.95" value={num(yoloDec.usda_test.yolo11.mAP50_95, 3)} />
                <Stat label="Sunflower test mAP@0.50" value={num(yoloDec.sunflower_test.yolo11.mAP50, 3)} hint={`pixel model ${num(yoloDec.sunflower_test.pixel.mAP50, 3)}`} />
                <Stat label="Sunflower test F1@0.5" value={num(yoloDec.sunflower_test.yolo11["f1@0.5"], 3)} />
              </div>
              <p className="mt-2 text-xs text-muted">Not trained on boxes for hibiscus, tomato, strawberry, brinjal or chilli (none exist) - detections on those crops are unvalidated. {yoloDec.licence_note}</p>
            </Card>
          )}
          <div className="kicker">{yoloDec?.deployed ? "Pixel detector (previous default; MIT fallback when the ONNX file is removed)" : "Deployed detector"}</div>
          <div className="grid grid-cols-2 gap-3 md:grid-cols-5">
            <Stat label="mAP@0.50" value={num(dep.test.mAP50, 3)} hint="test split" />
            <Stat label="mAP@0.50:0.95" value={num(dep.test.mAP50_95, 3)} />
            <Stat label="Precision@0.5" value={num(dep.test["precision@0.5"], 3)} hint="at lowest score" />
            <Stat label="Recall@0.5" value={num(dep.test["recall@0.5"], 3)} />
            <Stat label="F1@0.5" value={num(dep.test["f1@0.5"], 3)} />
          </div>
          <Notice>
            Detector trained on {det.data.train_images} images, tuned on {det.data.val_images}, tested once on {det.data.test_images} (USDA apple/peach/pear,
            CC BY 4.0) · {det.protocol} · generated {when(det.generated_at)} on {det.machine.cpu_count} CPU cores.
            Ground truth instances are mask components (touching flowers = one cluster) and background blossoms are unlabelled, which lowers measured precision.
          </Notice>
          <Card title="Baseline & ablation (same protocol)">
            <div className="overflow-x-auto"><table className="table-base">
              <thead><tr><th>Variant</th><th>val mAP50</th><th>test mAP50</th><th>test mAP50-95</th><th>P</th><th>R</th><th>pixel IoU</th><th>count MAE</th><th>ms / image</th></tr></thead>
              <tbody>{Object.entries(det.variants as AnyObj).map(([k, v]) => (
                <tr key={k} className={k === det.deployed_variant ? "font-medium" : ""}><td>{label(k)}{k === det.deployed_variant && " (deployed)"}</td>
                  <td className="font-mono">{num(v.val.mAP50, 3)}</td><td className="font-mono">{num(v.test.mAP50, 3)}</td><td className="font-mono">{num(v.test.mAP50_95, 3)}</td>
                  <td className="font-mono">{num(v.test["precision@0.5"], 3)}</td><td className="font-mono">{num(v.test["recall@0.5"], 3)}</td>
                  <td className="font-mono">{num(v.test_segmentation.pixel_IoU, 3)}</td><td className="font-mono">{num(v.test_counting.count_MAE, 1)}</td>
                  <td className="font-mono">{num(v.latency_ms_per_image_mean, 0)}</td></tr>
              ))}</tbody></table></div>
          </Card>
          <div className="grid gap-5 lg:grid-cols-2">
            <Card title="Per-species (test)">
              <table className="table-base"><thead><tr><th>Species</th><th>mAP50</th><th>mAP50-95</th><th>GT</th><th>Pred</th></tr></thead>
                <tbody>{Object.entries(dep.test_per_species as AnyObj).map(([k, v]) => <tr key={k}><td>{k}</td><td className="font-mono">{num(v.mAP50, 3)}</td><td className="font-mono">{num(v.mAP50_95, 3)}</td><td>{v.n_gt}</td><td>{v.n_pred}</td></tr>)}</tbody></table>
            </Card>
            <Card title="AP vs IoU threshold (test)">
              <ResponsiveContainer width="100%" height={200}>
                <LineChart data={Object.entries(dep.test.ap_per_iou as AnyObj).map(([k, v]) => ({ iou: k, ap: v }))}>
                  <CartesianGrid stroke="rgb(var(--line))" vertical={false} /><XAxis dataKey="iou" stroke="rgb(var(--muted))" fontSize={11} /><YAxis stroke="rgb(var(--muted))" fontSize={11} domain={[0, 1]} />
                  <Tooltip formatter={(v) => num(Number(v), 3)} /><Line dataKey="ap" stroke="rgb(var(--leaf))" strokeWidth={2} /></LineChart>
              </ResponsiveContainer>
            </Card>
            <Card title="Error analysis (test)">
              <div className="kicker mb-1">Recall by object size</div>
              <table className="table-base mb-3"><tbody>{Object.entries(dep.error_analysis.recall_by_gt_size_at_work_res as AnyObj).map(([k, v]) => <tr key={k}><td>{k}</td><td>{v.n_gt} GT</td><td className="font-mono">{pct(v["recall@0.5"])}</td></tr>)}</tbody></table>
              <div className="kicker mb-1">Hardest images</div>
              <table className="table-base"><tbody>{dep.error_analysis.worst_images.map((w: AnyObj) => <tr key={w.uid}><td className="font-mono text-xs">{w.uid}</td><td>{w.gt} GT / {w.pred} pred</td><td className="font-mono">AP50 {num(w.AP50, 3)}</td></tr>)}</tbody></table>
            </Card>
            {trade && (
              <Card title="Speed / accuracy trade-off" subtitle="chosen on validation, reported on test">
                <table className="table-base"><thead><tr><th>Side</th><th>Stride</th><th>val mAP50</th><th>test mAP50</th><th>ms</th></tr></thead>
                  <tbody>{trade.configs.map((c: AnyObj) => <tr key={`${c.side}-${c.stride}`}><td>{c.side}</td><td>{c.stride}</td><td className="font-mono">{num(c.val.mAP50, 3)}</td><td className="font-mono">{num(c.test.mAP50, 3)}</td><td className="font-mono">{num(c.test.latency_ms_mean, 0)}</td></tr>)}</tbody></table>
                <p className="mt-2 text-xs text-muted">Deployed: full analysis {trade.chosen.full.side}px / stride {trade.chosen.full.stride}; live scanning {trade.chosen.live.side}px.</p>
              </Card>
            )}
          </div>
          {sp && (
            <Card title="Species gallery (open-set)" subtitle={sp.caveat}>
              <div className="grid gap-5 lg:grid-cols-2">
                <div>
                  <div className="grid grid-cols-3 gap-2">
                    <Stat label="Open-set accuracy" value={pct(sp.test_open_set.accuracy)} />
                    <Stat label="Macro-F1" value={num(sp.test_open_set.macro_f1, 3)} />
                    <Stat label="Background rejected" value={pct(sp.test_background_rejection_rate)} />
                  </div>
                  <div className="kicker mb-1 mt-4">Leave-one-species-out (unseen species → unknown)</div>
                  <table className="table-base"><tbody>{Object.entries(sp.leave_one_species_out as AnyObj).map(([k, v]) => <tr key={k}><td>{k} removed</td><td className="font-mono">{pct(v.returned_unknown_fraction)} → unknown</td><td className="text-xs text-muted">{JSON.stringify(v.wrongly_assigned_to)}</td></tr>)}</tbody></table>
                </div>
                <div>
                  <div className="kicker mb-1">Confusion matrix (test, rows = truth)</div>
                  <table className="table-base text-center"><thead><tr><th />{sp.test_open_set.labels.map((l: string) => <th key={l} className="!text-center">{l}</th>)}</tr></thead>
                    <tbody>{sp.test_open_set.confusion_matrix.map((row: number[], i: number) => {
                      const tot = row.reduce((a, b) => a + b, 0) || 1;
                      return <tr key={i}><th>{sp.test_open_set.labels[i]}</th>{row.map((v, j) => <td key={j} className="font-mono" style={{ background: `rgb(var(--${i === j ? "leaf" : "alert"}) / ${(v / tot) * 0.6})` }}>{v}</td>)}</tr>;
                    })}</tbody></table>
                </div>
              </div>
            </Card>
          )}
          {(ext || sunDet) && (
            <Card title="Dataset extension: sunflower" subtitle="TF Flower Detection (CC BY 4.0) sunflower subset; species from tf flower_photos class folders">
              <div className="grid gap-5 lg:grid-cols-2">
                {ext && (
                  <div>
                    <div className="kicker mb-1">Species gallery (open-set, held-out crops)</div>
                    <table className="table-base"><tbody>
                      {Object.entries(ext.extra_species_test as AnyObj).map(([k, v]) => (
                        <tr key={k}><td>{k} recall</td><td className="font-mono">{pct(v.recall)}</td><td className="text-xs text-muted">{v.test_images} test crops · {pct(v.returned_unknown)} unknown</td></tr>
                      ))}
                      <tr><td>apple/peach/pear accuracy after extension</td><td className="font-mono">{pct(ext.usda_test_flowers_after_extension.accuracy)}</td><td /></tr>
                      <tr><td>background rejected after extension</td><td className="font-mono">{pct(ext.usda_background_rejection_after_extension)}</td><td /></tr>
                    </tbody></table>
                    <p className="mt-2 text-xs text-muted">{ext.caveat}</p>
                  </div>
                )}
                {sunDet && (
                  <div>
                    <div className="kicker mb-1">Deployed detector on sunflower test split (no retraining)</div>
                    <table className="table-base"><tbody>
                      <tr><td>mAP@0.50</td><td className="font-mono">{num(sunDet.metrics.mAP50, 3)}</td></tr>
                      <tr><td>recall@0.5</td><td className="font-mono">{num(sunDet.metrics["recall@0.5"], 3)}</td></tr>
                      <tr><td>images</td><td className="font-mono">{sunDet.images}</td></tr>
                    </tbody></table>
                    <p className="mt-2 text-xs text-muted">{sunDet.note} Sunflower detection needs a model trained on this data (e.g. YOLO11).</p>
                  </div>
                )}
              </div>
            </Card>
          )}
          {multi && (
            <Card title="Species recognition: all candidate species" subtitle={multi.caveat}>
              <div className="grid gap-5 lg:grid-cols-2">
                <div>
                  <div className="grid grid-cols-3 gap-2">
                    <Stat label="Test accuracy" value={pct(multi.test_overall.accuracy)} />
                    <Stat label="Test macro-F1" value={num(multi.test_overall.macro_f1, 3)} />
                    <Stat label="Enabled species" value={String(multi.enabled_species.length)} hint="of 9" />
                  </div>
                  <div className="kicker mb-1 mt-4">Pre-registered gating (validation): ≥{multi.gating_rule.min_references} refs, recall ≥{multi.gating_rule.min_val_recall}, precision ≥{multi.gating_rule.min_val_precision}</div>
                  <table className="table-base"><thead><tr><th>Species</th><th>Refs</th><th>val R</th><th>val P</th><th>Status</th></tr></thead>
                    <tbody>{Object.entries(multi.gating as AnyObj).map(([k, v]) => (
                      <tr key={k}><td>{k}</td><td>{v.references}</td><td className="font-mono">{num(v.val_recall ?? 0, 2)}</td><td className="font-mono">{num(v.val_precision ?? 0, 2)}</td>
                        <td>{v.enabled ? (multi.species_status?.[k] === "limited_evidence" ? `AI-supported · limited test evidence (${multi.test_support?.[k] ?? 0} images)` : "AI-supported · validated") : "not supported"}</td></tr>))}</tbody></table>
                  {multi.variant && <p className="mt-2 text-xs text-muted">Variant chosen on validation: <code>{multi.variant}</code> · {multi.background_references ?? 0} background references · threshold {num(multi.threshold, 3)}</p>}
                  <div className="kicker mb-1 mt-4">Test by source</div>
                  <table className="table-base"><tbody>{Object.entries(multi.test_by_source as AnyObj).map(([k, v]) => (
                    <tr key={k}><td>{label(k)}</td><td>{v.n}</td><td className="font-mono">{pct(v.report.accuracy)}</td></tr>))}</tbody></table>
                </div>
                <div>
                  <div className="kicker mb-1">Confusion matrix (all test sets, rows = truth)</div>
                  <div className="overflow-x-auto"><table className="table-base text-center text-xs"><thead><tr><th />{multi.test_overall.labels.map((l: string) => <th key={l} className="!text-center">{l}</th>)}</tr></thead>
                    <tbody>{multi.test_overall.confusion_matrix.map((row: number[], i: number) => {
                      const tot = row.reduce((a, b) => a + b, 0) || 1;
                      return <tr key={i}><th>{multi.test_overall.labels[i]}</th>{row.map((v, j) => <td key={j} className="font-mono" style={{ background: `rgb(var(--${i === j ? "leaf" : "alert"}) / ${(v / tot) * 0.6})` }}>{v}</td>)}</tr>;
                    })}</tbody></table></div>
                </div>
              </div>
            </Card>
          )}
          {yoloDec && (
            <Card title="Detector comparison (same evaluation code, held-out test)" subtitle={yoloDec.rule}>
              <table className="table-base"><thead><tr><th>Test set</th><th>Model</th><th>mAP50</th><th>mAP50-95</th><th>P</th><th>R</th><th>F1</th></tr></thead>
                <tbody>{(["usda_test", "sunflower_test"] as const).flatMap((t) => (["pixel", "yolo11"] as const).map((mname) => {
                  const r = yoloDec[t]?.[mname];
                  return r ? <tr key={t + mname}><td>{label(t)}</td><td>{mname}</td><td className="font-mono">{num(r.mAP50, 3)}</td><td className="font-mono">{num(r.mAP50_95, 3)}</td>
                    <td className="font-mono">{num(r["precision@0.5"], 3)}</td><td className="font-mono">{num(r["recall@0.5"], 3)}</td><td className="font-mono">{num(r["f1@0.5"], 3)}</td></tr> : null;
                }))}</tbody></table>
              <p className="mt-2 text-xs text-muted">Deployed: {yoloDec.deployed ? "YOLO11 (ONNX)" : "pixel detector (YOLO11 did not meet the rule)"} · {yoloDec.licence_note}</p>
            </Card>
          )}
          <Card title="YOLO11 (deep detector)">
            {yolo ? <p className="text-sm">Test mAP50 {num(yolo.test.mAP50, 3)} · mAP50-95 {num(yolo.test.mAP50_95, 3)} ({when(yolo.generated_at)})</p>
              : <p className="text-sm text-muted">No YOLO11 report yet. Train it with the CPU workflow <code>.github/workflows/yolo.yml</code> or the GPU notebook <code>notebooks/train_yolo11_colab.ipynb</code>; its report appears here automatically.</p>}
          </Card>
        </div>
      )}
    </div>
  );
}
